def update_workbook_qa():
    path = FINAL / "05_甬柜易算_研究报告引用与证据核对表.xlsx"
    workbook = load_workbook(path)
    sheet = workbook["QA"]
    updates = {
        "旧数据": ("通过", "未检出弃用结果"),
        "算法术语": ("通过", "未检出禁用称谓"),
        "SaaS边界": ("通过", "仅表述轻量原型"),
        "小程序/导出": ("通过", "未完成能力已明确"),
        "页码/目录": ("通过", "Word字段更新；主报告38页"),
        "图片": ("通过", "20幅正式图、23幅生成素材；来源完整"),
        "真实截图": ("通过", "本地真实运行；旧订单截图已排除"),
        "引用": ("通过", "正文[1]-[13]与文末一致"),
    }
    for row in range(2, sheet.max_row + 1):
        key = sheet.cell(row, 1).value
        if key in updates:
            sheet.cell(row, 3).value, sheet.cell(row, 4).value = updates[key]
    workbook.save(path)


